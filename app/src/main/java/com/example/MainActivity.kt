enum class AppTab(val title: String) {
    ROAST("Roast"),
    LIVE("Live Voice"),
    HISTORY("History"),
    ABOUT("About")
}

class MainActivity : ComponentActivity() {

    private val viewModel: RoastViewModel by viewModels()

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()

        setContent {
            MyApplicationTheme {
                MainAppContent(viewModel = viewModel)
            }
        }
    }
}

@Composable
fun MainAppContent(viewModel: RoastViewModel) {
    val context = LocalContext.current
    var currentTab by remember { mutableStateOf(AppTab.ROAST) }

    val targetName by viewModel.targetName.collectAsState()
    val description by viewModel.description.collectAsState()
    val selectedLanguage by viewModel.selectedLanguage.collectAsState()
    val selectedLevel by viewModel.selectedLevel.collectAsState()
    val selectedStyle by viewModel.selectedStyle.collectAsState()
    val uiState by viewModel.uiState.collectAsState()
    val isDemoMode by viewModel.isDemoMode.collectAsState()

    val allRoasts by viewModel.historyRoasts.collectAsState()
    val favoriteRoasts by viewModel.favoriteRoasts.collectAsState()

    // Live Voice states
    val liveMessages by viewModel.liveMessages.collectAsState()
    val isListening by viewModel.isListening.collectAsState()
    val isSpeaking by viewModel.isSpeaking.collectAsState()
    val isProcessingLive by viewModel.isProcessingLive.collectAsState()
    val audioLevel by viewModel.audioLevel.collectAsState()
    val liveTranscript by viewModel.liveTranscript.collectAsState()
    val isMuted by viewModel.isMuted.collectAsState()
    val liveError by viewModel.liveError.collectAsState()

    // Back handling
    BackHandler(enabled = currentTab != AppTab.ROAST || uiState !is RoastUiState.Idle) {
        if (uiState !is RoastUiState.Idle) {
            viewModel.roastAgain()
        } else if (currentTab != AppTab.ROAST) {
            currentTab = AppTab.ROAST
        }
    }

    val copyRoastToClipboard: (String) -> Unit = { text ->
        val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
        val clip = ClipData.newPlainText("AI Roast", text)
        clipboard.setPrimaryClip(clip)
        Toast.makeText(context, "Roast copied! 😂", Toast.LENGTH_SHORT).show()
    }

    val shareRoastText: (String) -> Unit = { text ->
        val sendIntent = Intent().apply {
            action = Intent.ACTION_SEND
            putExtra(Intent.EXTRA_TEXT, "😂 AI Roast:\n\n$text\n\n— Generated by AI Roast Generator 🔥")
            type = "text/plain"
        }
        val shareIntent = Intent.createChooser(sendIntent, "Share Roast 😂")
        context.startActivity(shareIntent)
    }

    Scaffold(
        modifier = Modifier
            .fillMaxSize()
            .background(DarkBackground),
        containerColor = DarkBackground,
        topBar = {
            RoastHeader(isDemoMode = isDemoMode)
        },
        bottomBar = {
            NavigationBar(
                containerColor = DarkSurface,
                tonalElevation = 8.dp,
                modifier = Modifier.testTag("bottom_nav_bar")
            ) {
                NavigationBarItem(
                    selected = currentTab == AppTab.ROAST,
                    onClick = { currentTab = AppTab.ROAST },
                    icon = {
                        Icon(
                            imageVector = Icons.Default.LocalFireDepartment,
                            contentDescription = "Roast"
                        )
                    },
                    label = { Text("Roast", fontSize = 11.sp) },
                    colors = NavigationBarItemDefaults.colors(
                        selectedIconColor = OrangeFlame,
                        selectedTextColor = OrangeFlame,
                        indicatorColor = OrangeFlame.copy(alpha = 0.2f),
                        unselectedIconColor = TextMuted,
                        unselectedTextColor = TextMuted
                    ),
                    modifier = Modifier.testTag("nav_tab_roast")
                )

                NavigationBarItem(
                    selected = currentTab == AppTab.LIVE,
                    onClick = { currentTab = AppTab.LIVE },
                    icon = {
                        Icon(
                            imageVector = Icons.Default.Mic,
                            contentDescription = "Live Voice"
                        )
                    },
                    label = { Text("Live Voice", fontSize = 11.sp) },
                    colors = NavigationBarItemDefaults.colors(
                        selectedIconColor = HotRed,
                        selectedTextColor = HotRed,
                        indicatorColor = HotRed.copy(alpha = 0.2f),
                        unselectedIconColor = TextMuted,
                        unselectedTextColor = TextMuted
                    ),
                    modifier = Modifier.testTag("nav_tab_live")
                )

                NavigationBarItem(
                    selected = currentTab == AppTab.HISTORY,
                    onClick = { currentTab = AppTab.HISTORY },
                    icon = {
                        Icon(
                            imageVector = Icons.Default.History,
                            contentDescription = "History"
                        )
                    },
                    label = { Text("History", fontSize = 11.sp) },
                    colors = NavigationBarItemDefaults.colors(
                        selectedIconColor = PurplePrimary,
                        selectedTextColor = PurplePrimary,
                        indicatorColor = PurplePrimary.copy(alpha = 0.2f),
                        unselectedIconColor = TextMuted,
                        unselectedTextColor = TextMuted
                    ),
                    modifier = Modifier.testTag("nav_tab_history")
                )

                NavigationBarItem(
                    selected = currentTab == AppTab.ABOUT,
                    onClick = { currentTab = AppTab.ABOUT },
                    icon = {
                        Icon(
                            imageVector = Icons.Default.Info,
                            contentDescription = "About"
                        )
                    },
                    label = { Text("About", fontSize = 11.sp) },
                    colors = NavigationBarItemDefaults.colors(
                        selectedIconColor = PurplePrimary,
                        selectedTextColor = PurplePrimary,
                        indicatorColor = PurplePrimary.copy(alpha = 0.2f),
                        unselectedIconColor = TextMuted,
                        unselectedTextColor = TextMuted
                    ),
                    modifier = Modifier.testTag("nav_tab_about")
                )
            }
        }
    ) { innerPadding ->
        Box(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
        ) {
            when (currentTab) {
                AppTab.ROAST -> {
                    RoastScreen(
                        targetName = targetName,
                        description = description,
                        selectedLanguage = selectedLanguage,
                        selectedLevel = selectedLevel,
                        selectedStyle = selectedStyle,
                        uiState = uiState,
                        onTargetNameChange = viewModel::onTargetNameChanged,
                        onDescriptionChange = viewModel::onDescriptionChanged,
                        onLanguageChange = viewModel::onLanguageSelected,
                        onLevelChange = viewModel::onLevelSelected,
                        onStyleChange = viewModel::onStyleSelected,
                        onRoastClick = viewModel::generateRoast,
                        onRandomClick = viewModel::applyRandomPreset,
                        onSelectVariation = viewModel::selectVariation,
                        onSaveRoast = viewModel::saveCurrentRoast,
                        onRoastAgain = viewModel::roastAgain,
                        onOpenLiveVoice = { currentTab = AppTab.LIVE },
                        onCopy = copyRoastToClipboard,
                        onShare = shareRoastText,
                        onDismissError = viewModel::dismissError
                    )
                }

                AppTab.LIVE -> {
                    LiveRoastScreen(
                        messages = liveMessages,
                        isListening = isListening,
                        isSpeaking = isSpeaking,
                        isProcessing = isProcessingLive,
                        audioLevel = audioLevel,
                        liveTranscript = liveTranscript,
                        isMuted = isMuted,
                        selectedLanguage = selectedLanguage,
                        quickPrompts = viewModel.quickPrompts,
                        liveError = liveError,
                        onToggleListening = viewModel::toggleListening,
                        onSendMessage = viewModel::sendLiveUserMessage,
                        onToggleMute = viewModel::toggleMute,
                        onReplayVoice = viewModel::speakAiMessage,
                        onClearBattle = viewModel::clearLiveBattle,
                        onDismissError = viewModel::dismissLiveError,
                        onLanguageChange = viewModel::onLanguageSelected,
                        onCopy = copyRoastToClipboard
                    )
                }

                AppTab.HISTORY -> {
                    HistoryScreen(
                        allRoasts = allRoasts,
                        favoriteRoasts = favoriteRoasts,
                        onToggleFavorite = viewModel::toggleFavorite,
                        onDelete = viewModel::deleteRoast,
                        onCopy = copyRoastToClipboard,
                        onShare = shareRoastText
                    )
                }

                AppTab.ABOUT -> {
                    AboutScreen(isDemoMode = isDemoMode)
                }
            }
        }
    }
}
